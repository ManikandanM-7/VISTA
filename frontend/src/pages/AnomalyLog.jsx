import { useState, useEffect } from "react";
import { ChevronDown, ChevronUp, Activity, BarChart2 } from "lucide-react";

const API = "http://localhost:8000";

const SEV = {
  critical: { bg:"#fff1f2", border:"#fca5a5", dot:"#ef4444", badgeBg:"#fee2e2", badgeColor:"#991b1b", badgeBorder:"#fca5a5" },
  moderate: { bg:"#fffbeb", border:"#fcd34d", dot:"#f59e0b", badgeBg:"#fef3c7", badgeColor:"#92400e", badgeBorder:"#fcd34d" },
  minor:    { bg:"#eff6ff", border:"#93c5fd", dot:"#3b82f6", badgeBg:"#dbeafe", badgeColor:"#1e40af", badgeBorder:"#93c5fd" },
  none:     { bg:"#f8fafc", border:"#e2e8f0", dot:"#94a3b8", badgeBg:"#f1f5f9", badgeColor:"#475569", badgeBorder:"#e2e8f0" },
};

function AnomalyCard({ ev }) {
  const [open, setOpen] = useState(false);
  const s = SEV[ev.severity] || SEV.none;

  return (
    <div style={{ background:s.bg, border:`1px solid ${s.border}`, borderRadius:16, overflow:"hidden", transition:"box-shadow .2s" }}>
      {/* Row */}
      <div style={{ display:"flex", alignItems:"center", gap:14, padding:"14px 20px", cursor:"pointer", userSelect:"none" }} onClick={() => setOpen(!open)}>
        <div style={{ width:10, height:10, borderRadius:"50%", background:s.dot, flexShrink:0 }} />
        <div style={{ flex:1, minWidth:0 }}>
          <div style={{ display:"flex", alignItems:"center", gap:10, marginBottom:4 }}>
            <span style={{ fontWeight:700, fontSize:14, color:"#0f172a", textTransform:"capitalize" }}>
              {ev.anomaly_type?.replace(/_/g," ") || "Unknown Anomaly"}
            </span>
            <span style={{ fontSize:11, fontWeight:700, padding:"2px 10px", borderRadius:99, letterSpacing:".05em",
              background:s.badgeBg, color:s.badgeColor, border:`1px solid ${s.badgeBorder}` }}>
              {(ev.severity||"—").toUpperCase()}
            </span>
          </div>
          <div style={{ fontSize:12, color:"#64748b", display:"flex", gap:16 }}>
            <span>{new Date(ev.timestamp).toLocaleString()}</span>
            <span className="mono">Score: {ev.anomaly_score?.toFixed(3) || "—"}</span>
            {ev.top_sensors?.length > 0 && <span>{ev.top_sensors.slice(0,2).join(", ")}</span>}
          </div>
        </div>
        <div style={{ display:"flex", alignItems:"center", gap:8, flexShrink:0 }}>
          {ev.rca_report && (
            <span style={{ fontSize:11, background:"#ede9fe", color:"#6d28d9", border:"1px solid #ddd6fe", borderRadius:99, padding:"3px 10px", fontWeight:600 }}>
              RCA
            </span>
          )}
          <div style={{ width:28, height:28, borderRadius:8, background:"rgba(0,0,0,0.04)", display:"flex", alignItems:"center", justifyContent:"center" }}>
            {open ? <ChevronUp size={14} color="#64748b"/> : <ChevronDown size={14} color="#94a3b8"/>}
          </div>
        </div>
      </div>

      {/* RCA Expand */}
      {open && ev.rca_report && (
        <div style={{ borderTop:`1px solid ${s.border}`, padding:"16px 20px", background:"rgba(255,255,255,.60)", backdropFilter:"blur(12px)" }}>
          <div style={{ fontSize:11, fontWeight:700, color:"#6366f1", marginBottom:10, letterSpacing:".08em", textTransform:"uppercase" }}>
            🔍 Root Cause Analysis
          </div>
          <div style={{ fontSize:13, color:"#334155", lineHeight:1.75, whiteSpace:"pre-wrap", background:"rgba(255,255,255,.70)", borderRadius:10, padding:"14px 16px", border:"1px solid rgba(255,255,255,.9)" }}>
            {ev.rca_report}
          </div>
          {ev.llm_backend && (
            <div style={{ marginTop:8, fontSize:11, color:"#94a3b8" }}>Generated by {ev.llm_backend}</div>
          )}
        </div>
      )}
    </div>
  );
}

export default function AnomalyLog() {
  const [events,  setEvents]  = useState([]);
  const [stats,   setStats]   = useState({});
  const [loading, setLoading] = useState(true);
  const [filter,  setFilter]  = useState("all");

  useEffect(() => {
    Promise.all([
      fetch(`${API}/anomalies/log?limit=50`).then(r=>r.json()),
      fetch(`${API}/anomalies/stats/summary`).then(r=>r.json()),
    ]).then(([log, s]) => {
      setEvents(log.events || []);
      setStats(s || {});
      setLoading(false);
    }).catch(() => setLoading(false));
  }, []);

  const counts = {
    all:      events.length,
    critical: events.filter(e=>e.severity==="critical").length,
    moderate: events.filter(e=>e.severity==="moderate").length,
    minor:    events.filter(e=>e.severity==="minor").length,
  };
  const filtered = filter === "all" ? events : events.filter(e => e.severity === filter);

  return (
    <div style={{ padding:"24px 32px", display:"flex", flexDirection:"column", gap:18 }}>

      {/* ── Header ── */}
      <div style={{ display:"flex", alignItems:"center", justifyContent:"space-between", flexWrap:"wrap", gap:12 }}>
        <div>
          <h1 style={{ fontSize:24, fontWeight:800, color:"#0f172a", letterSpacing:"-0.03em" }}>Anomaly Detection Log</h1>
          <p style={{ fontSize:13, color:"#64748b", marginTop:3 }}>AI-generated root cause analysis · LSTM Autoencoder</p>
        </div>

        {/* Filter tabs */}
        <div className="g-card" style={{ padding:4, display:"flex", gap:4, borderRadius:14 }}>
          {["all","critical","moderate","minor"].map(f => (
            <button key={f} onClick={() => setFilter(f)} style={{
              padding:"7px 16px", borderRadius:10, border:"none", cursor:"pointer",
              fontWeight:600, fontSize:13, display:"flex", alignItems:"center", gap:6, transition:"all .18s",
              background: filter===f ? "linear-gradient(135deg,#6366f1,#4f46e5)":"transparent",
              color: filter===f ? "white":"#64748b",
              boxShadow: filter===f ? "0 4px 12px rgba(99,102,241,.30)":"none",
              fontFamily:"inherit"
            }}>
              {f.charAt(0).toUpperCase()+f.slice(1)}
              <span style={{ fontSize:11, borderRadius:99, width:20, height:20, display:"flex", alignItems:"center", justifyContent:"center",
                background: filter===f ? "rgba(255,255,255,.25)":"rgba(99,102,241,.10)",
                color: filter===f ? "white":"#6366f1", fontWeight:700 }}>
                {counts[f]}
              </span>
            </button>
          ))}
        </div>
      </div>

      {/* ── Stats Row ── */}
      <div style={{ display:"grid", gridTemplateColumns:"repeat(4,1fr)", gap:14 }}>
        {[
          { label:"Total Anomaly Rows", val:stats.total_anomaly_rows?.toLocaleString(),                    color:"#ef4444" },
          { label:"Anomaly Rate",       val:stats.anomaly_rate_pct ? `${stats.anomaly_rate_pct}%`:"—",     color:"#f59e0b" },
          { label:"Fault Types Found",  val:Object.keys(stats.fault_type_counts||{}).length,               color:"#6366f1" },
          { label:"Dataset Size",       val:stats.total_simulation_rows?.toLocaleString(),                 color:"#64748b" },
        ].map(({ label, val, color }) => (
          <div key={label} className="g-card-strong" style={{ padding:"18px 22px", textAlign:"center" }}>
            <div className="mono" style={{ fontSize:26, fontWeight:800, color }}>{val ?? "—"}</div>
            <div style={{ fontSize:12, color:"#64748b", marginTop:6, fontWeight:500 }}>{label}</div>
          </div>
        ))}
      </div>

      {/* ── Fault Distribution ── */}
      {Object.keys(stats.fault_type_counts||{}).length > 0 && (
        <div className="g-card-strong" style={{ padding:20 }}>
          <div style={{ display:"flex", alignItems:"center", gap:8, marginBottom:14 }}>
            <BarChart2 size={15} color="#6366f1"/>
            <span style={{ fontSize:14, fontWeight:700, color:"#334155" }}>Fault Type Distribution</span>
          </div>
          <div style={{ display:"grid", gridTemplateColumns:"repeat(4,1fr)", gap:10 }}>
            {Object.entries(stats.fault_type_counts).map(([k, v]) => {
              const total = Object.values(stats.fault_type_counts).reduce((a,b)=>a+b, 0);
              const pct = Math.round(v / total * 100);
              return (
                <div key={k} style={{ background:"rgba(255,255,255,.65)", border:"1px solid rgba(99,102,241,.12)", borderRadius:12, padding:"12px 14px" }}>
                  <div style={{ fontSize:12, color:"#475569", marginBottom:8, fontWeight:500, textTransform:"capitalize" }}>
                    {k.replace(/_/g," ")}
                  </div>
                  <div style={{ display:"flex", justifyContent:"space-between", marginBottom:6 }}>
                    <span className="mono" style={{ fontWeight:700, color:"#6366f1", fontSize:15 }}>{v.toLocaleString()}</span>
                    <span style={{ fontSize:11, color:"#94a3b8" }}>{pct}%</span>
                  </div>
                  <div style={{ height:5, background:"#e0e7ff", borderRadius:99, overflow:"hidden" }}>
                    <div style={{ height:"100%", width:`${pct}%`, background:"linear-gradient(90deg,#6366f1,#3b82f6)", borderRadius:99 }}/>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* ── Events List ── */}
      <div style={{ display:"flex", flexDirection:"column", gap:10 }}>
        {loading && (
          <div className="g-card" style={{ padding:50, textAlign:"center" }}>
            <div style={{ width:36, height:36, border:"4px solid #e0e7ff", borderTopColor:"#6366f1", borderRadius:"50%", animation:"spin 1s linear infinite", margin:"0 auto 10px" }}/>
            <p style={{ color:"#64748b", fontSize:13 }}>Loading anomaly log…</p>
          </div>
        )}

        {!loading && filtered.length === 0 && (
          <div className="g-card" style={{ padding:60, textAlign:"center" }}>
            <Activity size={38} style={{ margin:"0 auto 12px", color:"#cbd5e1" }}/>
            <p style={{ color:"#64748b", fontSize:14, fontWeight:500 }}>
              {events.length === 0
                ? "No AI-analyzed anomalies yet. RCA reports appear when the live detector triggers."
                : `No ${filter} severity anomalies in the log.`}
            </p>
          </div>
        )}

        {filtered.map(ev => <AnomalyCard key={ev.id} ev={ev}/>)}
      </div>

    </div>
  );
}
